import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

/**
 * The generated migrations, folded into a source file.
 *
 * `migrate()` reads its folder from disk at run time, and openstrap ships as one executable with no
 * folder of its own (ADR 0001). So the statements are inlined here at build time instead: the schema
 * stays the only description of the tables, and what applies it travels inside the program.
 */
const generated = join(process.cwd(), "drizzle");
const migrations = readdirSync(generated, { withFileTypes: true })
  .filter((entry) => entry.isDirectory())
  .map((entry) => entry.name)
  .sort()
  .map((name) => ({
    name,
    statements: readFileSync(join(generated, name, "migration.sql"), "utf8")
      .split("--> statement-breakpoint")
      .map((statement) => statement.trim())
      .filter((statement) => statement.length > 0),
  }));

const source = `// Generated by \`npm run schema:migrations\`. Do not edit: change src/Store/Schema.ts instead.

/** One step from whatever a database is to what the schema says, and what it is called. */
export type Migration = {
  name: string;
  statements: readonly string[];
};

export const migrations: readonly Migration[] = ${JSON.stringify(migrations, null, 2)};
`;

writeFileSync(join(process.cwd(), "src/Store/Migrations.ts"), source);

console.log(`${migrations.length} migration(s) inlined into src/Store/Migrations.ts`);
